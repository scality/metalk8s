// MetalK8s's tool surface, built from the real tools.
//
// Nothing READS this at eval time. The eval loads gen/catalogue.json, which is generated from here
// and committed — so the surface a scenario is judged against is an artefact with a diff, rather
// than whatever HEAD happens to produce. catalogue.test.ts keeps the two in step.
//
// The catalogue worth evaluating is sometimes more than one product's: shell-ui merges every
// mounted micro-frontend's tools into a single model context, so the choice a model really makes
// is across all of them. mergeCatalogues() is how a second product's catalogue.json joins this one.

import { join } from 'path';
import { writeFileSync } from 'fs';
import { type Catalogue, buildCatalogue, catalogueTypes } from '@scality/webmcp-eval/v1';
import { createTools } from '../index';
import type { ToolContext } from '../types';

export const CATALOGUE_PATH = join(__dirname, 'gen', 'catalogue.json');

// The same surface as types, so a scenario's mock is checked against the tool it answers rather
// than against Record<string, unknown>. Generated from the catalogue and committed beside it:
// both are regenerated by the same command, so they cannot describe different tool sets.
//
// NOT named catalogue.d.ts: TypeScript would read that as the declaration file FOR catalogue.ts
// and shadow this module's own exports.
export const CATALOGUE_TYPES_PATH = join(__dirname, 'gen', 'toolArguments.d.ts');

export const writeCatalogueTypes = (catalogue: Catalogue): void =>
  writeFileSync(CATALOGUE_TYPES_PATH, catalogueTypes(catalogue, 'MetalK8sToolArguments'), 'utf8');

// No tool here touches `context` when it is CREATED — only inside execute(), which this never
// calls. So a stub is enough to read the name, description and inputSchema each one advertises,
// and the eval never needs a cluster, a token or a query client to build the catalogue.
const context = {} as unknown as ToolContext;

/** The release the surface was captured from. */
function productVersion(): string {
  return (process.env.METALK8S_VERSION || '0.0.0-dev').trim();
}

/**
 * The surface as the tools define it right now.
 *
 * Exactly the three fields the chat API's tool model accepts, and exactly the three a model reads
 * when it decides what to call. `annotations` is deliberately left out: the browser forwards it,
 * the agent endpoint does not take it, and a catalogue carrying it would 422 every request.
 */
export const buildFromTools = (): Catalogue =>
  buildCatalogue(
    'metalk8s-ui',
    productVersion(),
    createTools(context).map((tool) => ({ name: tool.name, description: tool.description, inputSchema: tool.inputSchema })),
  );
